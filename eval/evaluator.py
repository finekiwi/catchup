"""RAG pipeline evaluator using DeepEval metrics.

Metrics:
  - Faithfulness: hallucination control via propositional decomposition
  - ContextPrecision: relevance of top-k retrieved blocks
  - Citation Accuracy (G-Eval custom): source metadata accuracy in answers
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from utils.logging import log_api_call

try:
    from deepeval.metrics import FaithfulnessMetric, ContextualPrecisionMetric, GEval
    from deepeval.test_case import LLMTestCase, LLMTestCaseParams
except ImportError as _deepeval_err:
    raise ImportError(
        "deepeval not installed. Run: uv add deepeval"
    ) from _deepeval_err

LOGGER = logging.getLogger(__name__)

# Judge model is intentionally different from the answer generation model to avoid
# self-serving bias. When the answer model is gpt-4o-mini, use gpt-4o as the judge.
_JUDGE_MODEL_MAP: dict[str, str] = {
    "gpt-4o-mini": "gpt-4o",
    "gpt-4.1-mini": "gpt-4o",
    "gpt-4.1-nano": "gpt-4o",
    "gpt-4o": "gpt-4o",
    "claude-haiku-4-5-20251001": "gpt-4o",
    "claude-sonnet-4-6": "gpt-4o",
    "gemini-3-flash-preview": "gpt-4o",
    "gemini-3.1-flash-lite-preview": "gpt-4o",
    "gemini-3.1-pro-preview": "gpt-4o",
}

_DEFAULT_JUDGE_MODEL = "gpt-4o"

# Threshold for passing individual metrics
_PASS_THRESHOLD = 0.5


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------


@dataclass
class EvalCase:
    """Single evaluation case for the RAG pipeline.

    Attributes:
        question: The input question posed to the RAG system.
        expected_answer: The ground-truth reference answer from the golden set.
        actual_answer: The answer generated by the RAG pipeline.
        retrieved_contexts: List of raw text strings for each retrieved block.
        sources: List of source filenames cited in the actual answer.
        case_id: Optional identifier (e.g., gs_001) for tracing back to golden set.
        tier: Optional tier level (1-4) from the golden set.
    """

    question: str
    expected_answer: str
    actual_answer: str
    retrieved_contexts: list[str]
    sources: list[str] = field(default_factory=list)
    case_id: Optional[str] = None
    tier: Optional[int] = None


@dataclass
class CaseResult:
    """Evaluation result for a single EvalCase.

    Attributes:
        case_id: Identifier matching EvalCase.case_id.
        question: The original question.
        faithfulness_score: Score in [0, 1] measuring hallucination control.
        context_precision_score: Score in [0, 1] measuring retrieval relevance.
        citation_score: Score in [0, 1] measuring source citation accuracy.
        overall_score: Arithmetic mean of the three metric scores.
        passed: True if overall_score >= pass threshold.
        tier: Tier level from golden set (1-4).
        error: Error message if evaluation failed for this case.
    """

    case_id: Optional[str]
    question: str
    faithfulness_score: float
    context_precision_score: float
    citation_score: float
    overall_score: float
    passed: bool
    tier: Optional[int] = None
    error: Optional[str] = None


@dataclass
class EvalReport:
    """Aggregated evaluation report across all cases.

    Attributes:
        overall_score: Macro-average of all case overall_scores.
        faithfulness_score: Macro-average faithfulness across cases.
        context_precision_score: Macro-average context precision across cases.
        citation_score: Macro-average citation accuracy across cases.
        per_case_results: Detailed results for each evaluated case.
        total_cases: Total number of cases evaluated.
        passed_cases: Number of cases that passed the threshold.
        model: Answer generation model identifier.
        judge_model: LLM used as the evaluation judge.
        timestamp: ISO-8601 UTC timestamp when the report was generated.
    """

    overall_score: float
    faithfulness_score: float
    context_precision_score: float
    citation_score: float
    per_case_results: list[CaseResult]
    total_cases: int
    passed_cases: int
    model: str
    judge_model: str
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _resolve_judge_model(answer_model: str) -> str:
    """Return the judge model for a given answer model.

    Ensures the judge is different from (and generally stronger than) the answer model.
    """
    return _JUDGE_MODEL_MAP.get(answer_model, _DEFAULT_JUDGE_MODEL)


def _build_citation_metric(judge_model: str) -> GEval:
    """Build a G-Eval custom metric that checks source citation accuracy.

    The metric verifies whether the answer correctly references the source filenames
    or page numbers that correspond to the retrieved context blocks.

    Args:
        judge_model: OpenAI model name to use as the LLM judge for G-Eval.

    Returns:
        Configured GEval metric instance.
    """
    return GEval(
        name="Citation Accuracy",
        criteria=(
            "Evaluate whether the actual output correctly cites the source documents "
            "that support its claims. Check if filenames or page/cell references from "
            "the retrieval context appear in the answer where claims are made. "
            "Score 1.0 if all major claims are cited, 0.5 if some are cited, "
            "0.0 if no citations are present despite factual claims."
        ),
        evaluation_params=[
            LLMTestCaseParams.INPUT,
            LLMTestCaseParams.ACTUAL_OUTPUT,
            LLMTestCaseParams.RETRIEVAL_CONTEXT,
        ],
        model=judge_model,
        threshold=_PASS_THRESHOLD,
    )


def _evaluate_single_case(
    case: EvalCase,
    faithfulness_metric: FaithfulnessMetric,
    context_precision_metric: ContextualPrecisionMetric,
    citation_metric: GEval,
) -> CaseResult:
    """Run all three metrics against one EvalCase and return a CaseResult.

    Args:
        case: The evaluation case to score.
        faithfulness_metric: Configured FaithfulnessMetric instance.
        context_precision_metric: Configured ContextualPrecisionMetric instance.
        citation_metric: Configured citation GEval metric instance.

    Returns:
        CaseResult with all metric scores populated.
    """
    test_case = LLMTestCase(
        input=case.question,
        actual_output=case.actual_answer,
        expected_output=case.expected_answer,
        retrieval_context=case.retrieved_contexts,
    )

    faithfulness_score = 0.0
    context_precision_score = 0.0
    citation_score = 0.0
    error_msg: Optional[str] = None

    try:
        faithfulness_metric.measure(test_case)
        faithfulness_score = faithfulness_metric.score or 0.0
    except Exception as exc:
        LOGGER.warning("Faithfulness metric failed for case %s: %s", case.case_id, exc)
        error_msg = f"faithfulness: {exc}"

    try:
        context_precision_metric.measure(test_case)
        context_precision_score = context_precision_metric.score or 0.0
    except Exception as exc:
        LOGGER.warning("ContextPrecision metric failed for case %s: %s", case.case_id, exc)
        error_msg = (error_msg or "") + f" context_precision: {exc}"

    try:
        citation_metric.measure(test_case)
        citation_score = citation_metric.score or 0.0
    except Exception as exc:
        LOGGER.warning("Citation metric failed for case %s: %s", case.case_id, exc)
        error_msg = (error_msg or "") + f" citation: {exc}"

    overall = (faithfulness_score + context_precision_score + citation_score) / 3.0

    return CaseResult(
        case_id=case.case_id,
        question=case.question,
        faithfulness_score=round(faithfulness_score, 4),
        context_precision_score=round(context_precision_score, 4),
        citation_score=round(citation_score, 4),
        overall_score=round(overall, 4),
        passed=overall >= _PASS_THRESHOLD,
        tier=case.tier,
        error=error_msg,
    )


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def run_evaluation(cases: list[EvalCase], model: str = "gpt-4o-mini") -> EvalReport:
    """Evaluate RAG pipeline quality across a list of EvalCases.

    Runs three DeepEval metrics (Faithfulness, ContextualPrecision, Citation Accuracy)
    for each case using a separate judge model. Results are logged via log_api_call
    and can be saved to disk with save_report().

    Args:
        cases: List of EvalCase instances. Each must have actual_answer and
               retrieved_contexts populated from a real RAG pipeline run.
        model: The answer generation model identifier (used to select the judge).

    Returns:
        EvalReport aggregating scores across all cases.

    Raises:
        ValueError: If cases is empty.
    """
    if not cases:
        raise ValueError("cases must be non-empty")

    judge_model = _resolve_judge_model(model)
    LOGGER.info(
        "Starting evaluation: %d cases, answer_model=%s, judge_model=%s",
        len(cases), model, judge_model,
    )

    faithfulness_metric = FaithfulnessMetric(
        threshold=_PASS_THRESHOLD,
        model=judge_model,
        include_reason=True,
    )
    context_precision_metric = ContextualPrecisionMetric(
        threshold=_PASS_THRESHOLD,
        model=judge_model,
        include_reason=True,
    )
    citation_metric = _build_citation_metric(judge_model)

    per_case_results: list[CaseResult] = []
    t_start = time.perf_counter()

    for case in cases:
        LOGGER.debug("Evaluating case %s", case.case_id)
        result = _evaluate_single_case(
            case, faithfulness_metric, context_precision_metric, citation_metric
        )
        per_case_results.append(result)

    eval_latency_ms = (time.perf_counter() - t_start) * 1000

    # Aggregate scores
    n = len(per_case_results)
    agg_faithfulness = sum(r.faithfulness_score for r in per_case_results) / n
    agg_precision = sum(r.context_precision_score for r in per_case_results) / n
    agg_citation = sum(r.citation_score for r in per_case_results) / n
    agg_overall = sum(r.overall_score for r in per_case_results) / n
    passed = sum(1 for r in per_case_results if r.passed)

    # Log the evaluation run as an API call for cost/usage tracking
    log_api_call(
        model=judge_model,
        stage="eval_run",
        input_tokens=0,  # DeepEval manages token counting internally
        output_tokens=0,
        latency_ms=eval_latency_ms,
        cost_usd=0.0,
        success=True,
    )

    report = EvalReport(
        overall_score=round(agg_overall, 4),
        faithfulness_score=round(agg_faithfulness, 4),
        context_precision_score=round(agg_precision, 4),
        citation_score=round(agg_citation, 4),
        per_case_results=per_case_results,
        total_cases=n,
        passed_cases=passed,
        model=model,
        judge_model=judge_model,
    )

    LOGGER.info(
        "Evaluation complete: overall=%.4f, faithfulness=%.4f, precision=%.4f, citation=%.4f, passed=%d/%d",
        report.overall_score, report.faithfulness_score,
        report.context_precision_score, report.citation_score,
        passed, n,
    )
    return report


def save_report(report: EvalReport, output_dir: Path = Path("data/eval_results")) -> Path:
    """Persist an EvalReport to a timestamped JSON file.

    Args:
        report: The EvalReport to save.
        output_dir: Directory in which to write the report file.

    Returns:
        Path to the written JSON file.
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")
    out_path = output_dir / f"eval_report_{ts}.json"

    report_dict = asdict(report)
    out_path.write_text(json.dumps(report_dict, indent=2, ensure_ascii=False), encoding="utf-8")
    LOGGER.info("EvalReport saved to %s", out_path)
    return out_path


__all__ = ["EvalCase", "EvalReport", "CaseResult", "run_evaluation", "save_report"]

# v1.0.0 — initial judge prompts for binary answer correctness evaluation.
# Judge model must always differ from the answer generation model (anti-self-bias rule).
JUDGE_SYSTEM_PROMPT = (
    "You are an answer quality judge. Given a question, a reference answer, and a candidate answer, "
    "determine if the candidate answer is correct and sufficiently complete.\n"
    "Respond with exactly one word: CORRECT or INCORRECT."
)


def judge_user_prompt(question: str, expected_answer: str, actual_answer: str) -> str:
    """Format the user-turn prompt for the binary judge.

    Args:
        question: The original question posed to the RAG system.
        expected_answer: Ground-truth reference answer from the golden set.
        actual_answer: Candidate answer generated by the pipeline under evaluation.

    Returns:
        Formatted prompt string to send as the user message to the judge LLM.
    """
    return (
        f"Question: {question}\n\n"
        f"Reference answer: {expected_answer}\n\n"
        f"Candidate answer: {actual_answer}\n\n"
        "Is the candidate answer correct and sufficiently complete?"
    )


__all__ = ["JUDGE_SYSTEM_PROMPT", "judge_user_prompt"]
